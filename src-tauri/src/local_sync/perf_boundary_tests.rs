#[test]
fn perf_cached_feed_projection_recovers_after_trigger_failure_and_schema_change() {
    let c = fixture(0);
    let fields = cached_projection_variants(&c);
    let expected = projection_pass(&c, &fields, true, false);
    let before = snapshot(&c);
    c.execute_batch("CREATE TRIGGER perf_fail_feed_update BEFORE UPDATE ON feeds WHEN NEW.title='custom left' BEGIN SELECT RAISE(ABORT,'injected cached feed failure'); END; SAVEPOINT cached_failure; UPDATE local_sync_control SET applying=1 WHERE id=1").unwrap();
    assert!(database::apply_projection(&c, &fields[0], None).is_err());
    c.execute_batch("ROLLBACK TO cached_failure; RELEASE cached_failure")
        .unwrap();
    assert_eq!(
        snapshot(&c),
        before,
        "failed cached update must leave no partial projection or capture"
    );
    c.execute_batch("DROP TRIGGER perf_fail_feed_update")
        .unwrap();
    assert_eq!(projection_pass(&c, &fields, true, false), expected);
    assert_eq!(snapshot(&c), before);
}

/// Pre-fix production text, kept only to compare result sets. It joins two
/// references to the same relation; the production function no longer does that
/// because SQLite materializes the proposed view once per reference.
const LEGACY_ALIAS_SQL: &str = "SELECT substr(m.key,1,66)
 FROM local_sync_fields m
 JOIN local_sync_fields s
   ON s.key='s/'||json_extract(m.register,'$.value.value.source')||'/feed_url'
 WHERE m.key LIKE 'a/%/meta'
   AND json_extract(m.register,'$.value.value.guid')=?1
   AND json_extract(s.register,'$.value.value')=?2
 ORDER BY m.key";

fn legacy_alias_targets(c: &Connection, guid: &str, url: &str) -> Vec<String> {
    let mut stmt = c.prepare(LEGACY_ALIAS_SQL).unwrap();
    stmt.query_map(params![guid, url], |r| r.get::<_, String>(0))
        .unwrap()
        .collect::<rusqlite::Result<_>>()
        .unwrap()
}

fn explain_details(c: &Connection, sql: &str, guid: &str) -> Vec<String> {
    let mut stmt = c.prepare(&format!("EXPLAIN QUERY PLAN {sql}")).unwrap();
    stmt.query_map(params![guid], |r| r.get::<_, String>(3))
        .unwrap()
        .collect::<rusqlite::Result<_>>()
        .unwrap()
}

#[test]
fn alias_lookup_matches_legacy_double_join_result_set() {
    const SHARED_URL: &str = "https://example.test/shared";
    let c = conn();
    let (left_feed, _) = seed(&c, LEFT, "https://example.test/left");
    let folder: i64 = c
        .query_row(
            "SELECT folder_id FROM feeds WHERE id=?1",
            [left_feed],
            |r| r.get(0),
        )
        .unwrap();
    let right_feed = db::insert_feed(
        &c,
        "https://example.test/right",
        None,
        "Right",
        None,
        folder,
        "inherit",
        false,
        false,
    )
    .unwrap();
    c.execute(
        "UPDATE feeds SET sync_id=?1 WHERE id=?2",
        params![RIGHT, right_feed],
    )
    .unwrap();
    let article = db::NewArticle {
        guid: "shared-guid".into(),
        url: Some("https://example.test/shared-post".into()),
        title: "Original".into(),
        author: None,
        summary: Some("body".into()),
        content_html: Some("<p>body</p>".into()),
        body_text: "body".into(),
        image_url: None,
        enclosure_url: None,
        enclosure_mime: None,
        duration_sec: None,
        published_at: Some("2026-11-10T00:00:00Z".into()),
        source: "direct".into(),
    };
    db::upsert_article_with_feed(&c, left_feed, &article, false).unwrap();
    db::upsert_article_with_feed(&c, right_feed, &article, false).unwrap();
    let mut decoy = article.clone();
    decoy.guid = "other-guid".into();
    decoy.url = Some("https://example.test/other-post".into());
    db::upsert_article_with_feed(&c, left_feed, &decoy, false).unwrap();
    database::initialize(&c, LIB).unwrap();
    logical::drain_local(&c).unwrap();
    set_url(&c, LEFT, SHARED_URL);
    set_url(&c, RIGHT, SHARED_URL);
    logical::drain_local(&c).unwrap();

    let mut expected = vec![
        format!("a/{}", model::entry_key(LEFT, "shared-guid")),
        format!("a/{}", model::entry_key(RIGHT, "shared-guid")),
    ];
    expected.sort();
    let legacy = legacy_alias_targets(&c, "shared-guid", SHARED_URL);
    assert_eq!(legacy, expected, "legacy fixture must expose both aliases");
    let lookup =
        logical::article_alias_targets_for_test(&c, logical::WINNERS, "shared-guid", SHARED_URL)
            .unwrap();
    assert_eq!(
        lookup, legacy,
        "the GUID-seek rewrite must match the old double-join result set"
    );
    let wrong = logical::article_alias_targets_for_test(
        &c,
        logical::WINNERS,
        "shared-guid",
        "https://example.test/elsewhere",
    )
    .unwrap();
    assert_eq!(wrong, Vec::<String>::new());
    assert_eq!(
        wrong,
        legacy_alias_targets(&c, "shared-guid", "https://example.test/elsewhere")
    );

    // The proposed view is what whole-library preflight actually queries.
    logical::proposed_view_for_test(&c, &"0".repeat(64)).unwrap();
    let lookup_view = logical::article_alias_targets_for_test(
        &c,
        "temp.local_sync_proposed",
        "shared-guid",
        SHARED_URL,
    )
    .unwrap();
    assert_eq!(
        lookup_view, legacy,
        "the proposed-view branch must return the same entries in the same order"
    );
}

